#!/usr/bin/env python3
"""Regenerates src/common/diagnostic_codes.inc from docs/diagnostics.md.

docs/diagnostics.md is the single source of truth for the diagnostic catalog
(code, category/severity, stage, trigger, subject and fix); `ptpn explain`
serves the same table. The generated `.inc` is checked in so the CLI has no
runtime dependency on the docs, and `test/test_explain.cpp` fails when the two
drift apart.

Usage: python3 tools/gen_diagnostic_codes.py
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "diagnostics.md"
OUT = ROOT / "src" / "common" / "diagnostic_codes.inc"

CODE_RE = re.compile(r"^`([ER]-[A-Z]+-\d+)`$")

CATEGORY_BY_PREFIX = {
    "E-SYN": "syntax",
    "E-VAL": "validation",
    "E-UNS": "unsupported",
    "E-PERF": "performance",
    "E-INT": "internal",
    "R-ANA": "analysis",
}


def strip_markdown(text: str) -> str:
    return text.replace("**", "").strip()


def category_for(code: str) -> str:
    for prefix, category in CATEGORY_BY_PREFIX.items():
        if code.startswith(prefix + "-"):
            return category
    return "internal"


def split_category(text: str) -> tuple[str, str]:
    text = strip_markdown(text)
    if "/" in text:
        category, severity = text.split("/", 1)
        return category.strip(), severity.strip()
    return "", text


CELL_SPLIT = re.compile(r"(?<!\\)\|")


def split_cells(line: str) -> list[str]:
    """Splits a Markdown table row, honouring `\\|` escapes inside cells."""
    cells = CELL_SPLIT.split(line.strip().strip("|"))
    return [cell.replace("\\|", "|").strip() for cell in cells]


def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main() -> int:
    lines = DOC.read_text(encoding="utf-8").splitlines()
    entries: list[tuple[str, ...]] = []
    group = ""
    index = 0
    while index < len(lines):
        line = lines[index]
        if line.startswith("### "):
            group = line[4:].strip()
        elif line.startswith("## "):
            group = line[3:].strip()

        is_code_table = (
            line.startswith("|")
            and "Code" in line
            and ("Cat./sev." in line or "Sev." in line)
        )
        if not is_code_table:
            index += 1
            continue

        index += 2  # skip the header and the separator row
        while index < len(lines) and lines[index].startswith("|"):
            cells = split_cells(lines[index])
            match = CODE_RE.match(cells[0]) if cells else None
            if match:
                # The row shape decides the columns: six cells carry an extra
                # stage column and a combined "category/severity" cell, five
                # cells only a severity.
                if len(cells) == 6:
                    code, catsev, stage, trigger, subject, fix = cells
                elif len(cells) == 5:
                    code, catsev, trigger, subject, fix = cells
                    stage = group
                else:
                    print(f"row for {cells[0]} has {len(cells)} cells", file=sys.stderr)
                    return 1
                category, severity = split_category(catsev)
                if not category:
                    # The code cell keeps its backticks; the lookup needs the
                    # bare code.
                    category = category_for(match.group(1))
                entries.append(
                    (
                        match.group(1),
                        category,
                        severity,
                        stage,
                        trigger,
                        subject,
                        fix,
                        group,
                    )
                )
            index += 1
        continue

    # The doc may document one code in two tables (for example E-VAL-033 in
    # both the envelope table and the JSON validation table). Keep the first row
    # and merge the second stage into it.
    unique: list[list[str]] = []
    seen: dict[str, int] = {}
    for entry in entries:
        if entry[0] in seen:
            position = seen[entry[0]]
            stage = unique[position][3]
            extra = entry[3]
            if extra and extra not in stage:
                unique[position][3] = f"{stage}; {extra}" if stage else extra
            continue
        seen[entry[0]] = len(unique)
        unique.append(list(entry))
    if not unique:
        print("no diagnostic code tables found in docs/diagnostics.md", file=sys.stderr)
        return 1

    lines_out = [
        "// Generated by tools/gen_diagnostic_codes.py from docs/diagnostics.md.",
        "// Do not edit by hand: edit the doc and re-run the script.",
        "//",
        "// {code, category, severity, stage, trigger, subject, fix, group}",
    ]
    for entry in unique:
        fields = ", ".join(f'"{escape(field)}"' for field in entry)
        lines_out.append("    {" + fields + "},")
    OUT.write_text("\n".join(lines_out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} with {len(unique)} codes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
