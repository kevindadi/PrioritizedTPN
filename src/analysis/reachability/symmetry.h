#ifndef ANALYSIS_REACHABILITY_SYMMETRY_H
#define ANALYSIS_REACHABILITY_SYMMETRY_H

#include <cstddef>
#include <string>
#include <vector>

#include "analysis/reachability/state_class.h"
#include "model/petri.h"

namespace state_class {

// A bijection on the nodes of a PTPN, induced by permuting tasks. The arrays
// map an old index to its image (old -> new).
struct NetPermutation {
  std::vector<size_t> places;
  std::vector<size_t> transitions;
};

// A verified net permutation together with the inverse node maps, used to
// apply the permutation to a state class and to rebuild its clock layout.
struct SymmetryGroupElement {
  NetPermutation forward;
  std::vector<size_t> place_inverse;
  std::vector<size_t> transition_inverse;
};

// Symmetry quotient of a PTPN under permutations of structurally identical
// tasks.
//
// Scope and soundness (deliberately conservative):
//
//  * Tasks come from net.node_pn_map()/net.task_info(); a net without task
//    metadata is left untouched.
//  * A task signature describes the chain (node kinds, place capacities, time
//    intervals, priority, core behaviour, suspendability, periodic marker),
//    lock names, period/deadline and the external arcs attached to the chain
//    (consumers, period cells, core resources, dependency edges, including the
//    chain signature of the neighbouring task). Only equal signatures are
//    candidates for a swap.
//  * A candidate swap is used only after the induced place/transition
//    permutation has been verified as an automorphism of the whole net:
//    pre/post arcs and weights, place capacity/saturation/initial tokens,
//    transition interval/priority/suspendability, and a consistent (possibly
//    non-identity) relabelling of core ids with matching core parallelism.
//    The control core must stay fixed.
//  * A signature group is dropped when one of its lock names is also used by a
//    task outside the group ("do not share locks with non-isomorphic tasks").
//  * Symmetry is applied only to tasks that are bound to *distinct real cores*
//    (core id >= 0). Control-core tasks and several tasks sharing one real core
//    are left unpermuted: on a shared core the canonical representative chooses
//    which task runs, and per-task timing metrics would no longer be recoverable
//    from the reduced graph. This is the conservative subset allowed by the
//    task specification; cores still need not have the same numeric id, only
//    the same parallelism (the verifier builds the core relabelling).
//  * Accepted swaps are generated by a spanning tree of the admissible pairs,
//    so the generated group is a group of net automorphisms even when some
//    pairs are not directly admissible. Group elements are enumerated up to
//    kMaxGroupOrder; if adding a generator would exceed that cap it is skipped.
//    The remaining subgroup is still sound, so the reduction may be partial
//    but never merges non-isomorphic behaviour.
//
// What is canonicalized: every identity-bearing field of a StateClass, i.e.
// marking, clock_vars (and the derived per-transition clock maps),
// priority_enabled/suspended, the DBM rows and columns, and the resulting
// lexical key. elapsed_time and id are metadata and are not part of the orbit
// key.
//
// Dependency edges between swapped tasks are supported only when the induced
// permutation really is an automorphism (mirrored structure); otherwise the
// swap is rejected and the tasks are explored separately. Periodic transitions
// must be fixed by the permutation so that the per-task periodic metadata used
// by the deadlock analysis stays aligned with the graph edge labels; in
// practice this keeps periodic tasks with distinct release transitions
// unpermuted, which is the safe choice.
class TaskSymmetry {
 public:
  static constexpr size_t kMaxGroupOrder = 720;  // |S_6|

  explicit TaskSymmetry(const petri::PTPN& net);

  [[nodiscard]] bool has_nontrivial_group() const {
    return elements_.size() > 1;
  }

  [[nodiscard]] size_t group_order() const {
    return elements_.size();
  }

  // Task-name groups whose members are provably interchangeable. Each group
  // has at least two members.
  [[nodiscard]] const std::vector<std::vector<std::string>>& task_groups() const {
    return task_groups_;
  }

  // Lexicographically smallest representative of the orbit of `state` under the
  // verified permutation group. Returns `state` unchanged when the group is
  // trivial.
  [[nodiscard]] StateClass canonicalize(StateClass state) const;

 private:
  const petri::PTPN& net_;
  std::vector<SymmetryGroupElement> elements_;
  std::vector<std::vector<std::string>> task_groups_;

  [[nodiscard]] StateClass apply(const StateClass& state,
                                 const SymmetryGroupElement& element) const;
};

}  // namespace state_class

#endif  // ANALYSIS_REACHABILITY_SYMMETRY_H
