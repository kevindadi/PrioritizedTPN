#!/usr/bin/env python3
"""Build a single-file, server-free demo of the PTPN workbench.

The output embeds the fragment page, stylesheet, application script, and the
precomputed demo payload into one HTML document. It can be opened directly from
disk or shared as a single file; no local server or network is required beyond
the optional Google Fonts request (the page has real fallback stacks).

Usage:
    python3 webapp/make_demo.py
    python3 webapp/build_standalone.py [OUTPUT_PATH]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent
DEFAULT_OUTPUT = ROOT / "demo" / "ptpn-chronograph-demo.html"


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        raise SystemExit("error: could not read {}: {}".format(path, exc))


def _script_safe(text: str) -> str:
    return text.replace("</script", "<\\/script")


def build(output: Path) -> int:
    page = _read(ROOT / "static" / "index.html")
    css = _read(ROOT / "static" / "style.css")
    app_js = _read(ROOT / "static" / "app.js")
    demo_js = _read(ROOT / "demo" / "demo-data.js")

    # Keep the font links, drop the local stylesheet link.
    links = re.findall(r"<link[^>]*>", page)
    font_links = "\n".join(
        link for link in links if "fonts.googleapis.com" in link or "fonts.gstatic.com" in link
    )
    body = re.sub(r'<meta name="claude:viewport-fit-sides"[^>]*>\s*', "", page)
    body = re.sub(r"<title>.*?</title>\s*", "", body, flags=re.S)
    body = re.sub(r"<link[^>]*>\s*", "", body)
    body = re.sub(r'<script src="demo-data\.js"></script>\s*', "", body)
    body = re.sub(r'<script src="app\.js"></script>\s*', "", body)

    document = """<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>PTPN Chronograph</title>
<!-- Generated by webapp/build_standalone.py; do not edit by hand. -->
{font_links}
<style>
{css}
</style>
</head>
<body>
{body}
<script>
{demo_js}
</script>
<script>
{app_js}
</script>
</body>
</html>
""".format(
        font_links=font_links,
        css=_script_safe(css),
        body=body,
        demo_js=_script_safe(demo_js),
        app_js=_script_safe(app_js),
    )

    output = output.resolve()
    try:
        output.parent.mkdir(parents=True, exist_ok=False)
    except FileExistsError:
        pass
    except OSError as exc:
        raise SystemExit("error: could not create {}: {}".format(output.parent, exc))
    try:
        output.write_text(document, encoding="utf-8")
    except OSError as exc:
        raise SystemExit("error: could not write {}: {}".format(output, exc))

    print("Wrote {} ({:.1f} KB)".format(output, len(document.encode("utf-8")) / 1024.0))
    return 0


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if len(argv) > 1:
        print("usage: python3 webapp/build_standalone.py [OUTPUT_PATH]", file=sys.stderr)
        return 2
    output = Path(argv[0]) if argv else DEFAULT_OUTPUT
    return build(output)


if __name__ == "__main__":
    raise SystemExit(main())
